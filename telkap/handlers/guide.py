def _menu() -> InlineKeyboardBuilder:
    kb = InlineKeyboardBuilder()
    for row in LAYOUT:
        kb.row(
            *[
                InlineKeyboardButton(text=SECTIONS[key][0], callback_data=f"guide:{key}")
                for key in row
            ]
        )
    return kb


def _section_keyboard(current: str) -> InlineKeyboardBuilder:
    """پایین هر بخش: رفتن به بخش بعد و بازگشت به فهرست."""
    keys = list(SECTIONS)
    index = keys.index(current)
    kb = InlineKeyboardBuilder()
    if index + 1 < len(keys):
        nxt = keys[index + 1]
        kb.row(
            InlineKeyboardButton(
                text=f"➡️ بعدی: {SECTIONS[nxt][0]}", callback_data=f"guide:{nxt}"
            )
        )
    kb.row(InlineKeyboardButton(text="📚 فهرست راهنما", callback_data="guide:home"))
    return kb


@router.message(Command("help"))
@router.message(Command("guide"))
@router.message(F.text == BTN_HELP)
async def cmd_help(message: Message) -> None:
    await message.answer(_home(), reply_markup=_menu().as_markup())


@router.callback_query(F.data == "guide:home")
async def cb_home(call: CallbackQuery) -> None:
    await call.answer()
    try:
        await call.message.edit_text(_home(), reply_markup=_menu().as_markup())
    except Exception:
        await call.message.answer(_home(), reply_markup=_menu().as_markup())


@router.callback_query(F.data.startswith("guide:"))
async def cb_section(call: CallbackQuery) -> None:
    key = call.data.split(":", 1)[1]
    section = SECTIONS.get(key)
    if section is None:
        await call.answer()
        return
    await call.answer()
    text = section[1]()
    markup = _section_keyboard(key).as_markup()
    try:
        await call.message.edit_text(text, reply_markup=markup)
    except Exception:
        await call.message.answer(text, reply_markup=markup)
