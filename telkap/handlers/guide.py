def _title(key: str, lang: str | None = None) -> str:
    """عنوان دکمه‌ی بخش؛ اگر ترجمه نشده باشد فارسی می‌ماند."""
    return guide_texts.title(key, i18n.normalize(lang or i18n.current())) or SECTIONS[key][0]


def _fields(key: str, lang: str) -> dict[str, str]:
    """جاهای خالیِ وابسته به قیمت و سقف، برای متنِ ترجمه‌شده‌ی این بخش.

    این چند بخش را نمی‌شود دربست ترجمه کرد: عددهایشان از `plans.py` می‌آید
    و ادمین می‌تواند از پنل عوضشان کند. پس متن ترجمه می‌شود و عددها هر بار
    تازه جاشان می‌نشینند.
    """
    if key == "plans":
        return {"table": _plans_table(lang), "custom": _plan_title(CUSTOM, lang)}
    if key == "credits":
        return {"wm_price": _wm_price(lang), "hist_price": _hist_price(lang)}
    if key == "faq":
        return {"two_week": _plan_title(TWO_WEEK, lang)}
    if key == "faqpay":
        return {"custom": _plan_title(CUSTOM, lang)}
    return {}


def _body(key: str, lang: str | None = None) -> str:
    """متن بخش؛ اگر ترجمه نشده باشد فارسی می‌ماند."""
    code = i18n.normalize(lang or i18n.current())
    return guide_texts.body(key, code, **_fields(key, code)) or SECTIONS[key][1]()


def _home(lang: str | None = None) -> str:
    return guide_texts.body("home", i18n.normalize(lang or i18n.current())) or _home_fa()


def _menu(lang: str | None = None) -> InlineKeyboardBuilder:
    kb = InlineKeyboardBuilder()
    for row in LAYOUT:
        kb.row(
            *[
                InlineKeyboardButton(text=_title(key, lang), callback_data=f"guide:{key}")
                for key in row
            ]
        )
    return kb


def _section_keyboard(current: str, lang: str | None = None) -> InlineKeyboardBuilder:
    """پایین هر بخش: رفتن به بخش بعد و بازگشت به فهرست."""
    keys = list(SECTIONS)
    index = keys.index(current)
    kb = InlineKeyboardBuilder()
    if index + 1 < len(keys):
        nxt = keys[index + 1]
        kb.row(
            InlineKeyboardButton(
                text=f"➡️ {_title(nxt, lang)}", callback_data=f"guide:{nxt}"
            )
        )
    kb.row(
        InlineKeyboardButton(
            text=i18n.t("menu.help", lang), callback_data="guide:home"
        )
    )
    return kb


@router.message(Command("help"))
@router.message(Command("guide"))
@router.message(F.text.in_(menu_texts("menu.help")))
async def cmd_help(message: Message) -> None:
    await message.answer(_home(), reply_markup=_menu().as_markup())


@router.callback_query(F.data == "guide:home")
async def cb_home(call: CallbackQuery) -> None:
    await call.answer()
    try:
        await call.message.edit_text(_home(), reply_markup=_menu().as_markup())
    except Exception:
        await call.message.answer(_home(), reply_markup=_menu().as_markup())


@router.callback_query(F.data.startswith("guide:"))
async def cb_section(call: CallbackQuery) -> None:
    key = call.data.split(":", 1)[1]
    section = SECTIONS.get(key)
    if section is None:
        await call.answer()
        return
    await call.answer()
    text = _body(key)
    markup = _section_keyboard(key).as_markup()
    try:
        await call.message.edit_text(text, reply_markup=markup)
    except Exception:
        await call.message.answer(text, reply_markup=markup)
