async def accepted(user_id: int) -> bool:
    """آیا این کاربر <b>نسخه‌ی فعلی</b> را پذیرفته است."""
    async with get_session() as db:
        version = await db.scalar(
            select(User.terms_version).where(User.id == user_id)
        )
    return bool(version) and int(version) >= VERSION


async def accept(user_id: int) -> None:
    """پذیرش را با نسخه و زمانش ثبت می‌کند.

    زمان ثبت می‌شود چون بدون آن، پذیرش قابل استناد نیست: باید بشود
    گفت «این کاربر، این متن را، این تاریخ پذیرفت».
    """
    async with get_session() as db:
        user = await db.get(User, user_id)
        if user is None:
            return
        user.terms_version = VERSION
        user.terms_accepted_at = datetime.now(UTC)
        await db.commit()
